"""LoRA (Low-Rank Adaptation) for XIIV — surgical training on limited hardware.

Instead of training all 916M params (needs 10GB+ RAM), we:
1. FREEZE the entire base model (no gradients, no optimizer state)
2. Add tiny low-rank adapter matrices to each attention layer
3. Train ONLY the adapters (~3-5M params instead of 916M)

Memory: ~4GB total (model weights fp32 frozen + adapters + grads + Adam for adapters only)
This fits in 7GB RAM and runs on CPU.

CNaRA (Contract-conditioned Noise-aware Rank Adaptation), also in this module:
an extension of the static LoRA above where the low-rank update is modulated
by a lightweight globally-shared hypernetwork conditioned on (a) the diffusion
noise level and (b) XIIV's contract-conditioning signal. See the CNaRA section
below for the design and prior-art statement.
"""
import math

import torch
import torch.nn as nn
import torch.nn.functional as F


class LoRALinear(nn.Module):
    """Wraps nn.Linear with a trainable low-rank bypass. Base weights frozen."""

    def __init__(self, base: nn.Linear, rank: int = 8, alpha: float = 16.0):
        super().__init__()
        self.base = base
        # Freeze base
        for p in self.base.parameters():
            p.requires_grad = False

        d_in, d_out = base.in_features, base.out_features
        self.lora_A = nn.Parameter(torch.randn(rank, d_in) * 0.01)
        self.lora_B = nn.Parameter(torch.zeros(d_out, rank))
        self.scaling = alpha / rank

    def forward(self, x):
        base_out = self.base(x)
        lora_out = (x @ self.lora_A.T @ self.lora_B.T) * self.scaling
        return base_out + lora_out

    def trainable_params(self):
        return sum(p.numel() for p in [self.lora_A, self.lora_B])


def inject_lora(model, rank=8, alpha=16.0, target_modules=("qkv", "out")):
    """Replace target Linears in all attention layers with LoRA wrappers.
    Returns count of trainable params."""
    total = 0
    for block in model.layers:
        for name in target_modules:
            orig = getattr(block.attn, name)
            if isinstance(orig, LoRALinear):
                raise ValueError(
                    f"block already has a LoRA/CNaRA adapter on {name}: "
                    "refusing double injection")
            lora = LoRALinear(orig, rank=rank, alpha=alpha)
            setattr(block.attn, name, lora)
            total += lora.trainable_params()
    # Also ensure everything else is frozen
    for name, p in model.named_parameters():
        if "lora_" not in name:
            p.requires_grad = False
    return total


def get_trainable_params(model):
    return sum(p.numel() for p in model.parameters() if p.requires_grad)


def merge_lora(model):
    """Fold LoRA weights back into base for deployment (optional)."""
    for block in model.layers:
        for name in ("qkv", "out"):
            mod = getattr(block.attn, name)
            if isinstance(mod, CNARALinear):
                raise ValueError(
                    "merge_lora cannot fold CNaRA adapters: the effective "
                    "update B.S(λ,c).A depends on the noise/contract "
                    "condition. Use merge_cnara(model, lam, contract) with "
                    "the deployment condition instead.")
            if isinstance(mod, LoRALinear):
                with torch.no_grad():
                    # forward: x @ A.T @ B.T == x @ (B@A).T, and base(x) ==
                    # x @ W.T, so the fold is W += scaling * (B@A) — no
                    # transpose (the old `.T` here was a shape bug: it
                    # errored on non-square linears and silently folded the
                    # transposed update on square ones).
                    delta = (mod.lora_B @ mod.lora_A) * mod.scaling
                    mod.base.weight += delta
                setattr(block.attn, name, mod.base)
    return model


# ---------------------------------------------------------------------------
# CNaRA: Contract-conditioned Noise-aware Rank Adaptation
# ---------------------------------------------------------------------------
# Prior art (adopted, cited — not invented here):
#   NaRA — "Noise-Aware LoRA for Parameter-Efficient Fine-Tuning of Diffusion
#   LLMs" (Wang, Zhuang, Huang, Zhang, arXiv:2605.29716, May 2026).
#   Standard LoRA is noise-agnostic, but in diffusion LMs the input
#   distribution and generation difficulty shift along the denoising
#   trajectory. NaRA introduces a low-rank core matrix S generated by a
#   lightweight, globally-shared hypernetwork conditioned on the noise
#   level, so the effective update ΔW = B·S(λ)·A varies continuously along
#   the trajectory with negligible parameter/latency overhead.
#
# XIIV's extension (claimed novel-in-combination; no published prior art
# found as of 2026-10-16): the hypernetwork is ALSO conditioned on XIIV's
# contract signal — whether the current batch carries contract conditioning
# (XIIV trains ~40% of batches contract-conditioned). So
#   ΔW = scaling · B · S(λ, c) · A,   S(λ, c) = I + η · core(λ, c),
# where λ is the batch noise level (mask ratio) and c ∈ {0, 1} is the
# contract flag. NaRA conditions on noise only; no published work combines
# guarantee-native contract conditioning with noise-aware PEFT.
#
# Safe rollout: the hypernetwork's final layer is zero-initialized, so
# S(λ, c) = I at init and a CNaRA adapter behaves EXACTLY like static LoRA
# until the hypernetwork learns something. Extra params: ~5K (hypernet) vs
# ~2.2M (adapters) — negligible on the CPU training loop.
#
# Honest scope: NaRA's gains were shown at 8B scale on GPU; the improvement
# at XIIV's scale on CPU is UNVERIFIED — measure masked-LM loss vs static
# LoRA on a held-out slice before claiming anything. See research/cnara_2026.md.


def fourier_features(lam, k: int = 8) -> torch.Tensor:
    """Fourier embedding of scalar noise level(s) in [0, 1].

    Returns (..., 2*k): [sin(π·λ), sin(2π·λ), …, cos(π·λ), …].
    Accepts a float or a 0-d/1-d tensor; clamped to [0, 1].
    """
    if not torch.is_tensor(lam):
        lam = torch.tensor(float(lam), dtype=torch.float32)
    lam = lam.to(torch.float32).clamp(0.0, 1.0)
    freqs = torch.arange(1, int(k) + 1, dtype=torch.float32,
                         device=lam.device) * math.pi
    ang = lam.unsqueeze(-1) * freqs                      # (..., k)
    return torch.cat([torch.sin(ang), torch.cos(ang)], dim=-1)


class CNARAHyperNet(nn.Module):
    """(λ, c) → r×r core offset. S(λ, c) = I + η · reshape(MLP([F(λ); E(c)])).

    F(λ): Fourier features (no learned params). E(c): learned 2×d embedding
    of the contract flag (zero-init). Final MLP layer zero-init → S = I at
    init (safe rollout: identical to static LoRA until trained).
    """

    def __init__(self, rank: int, fourier_k: int = 8, hidden: int = 64,
                 contract_dim: int = 4, eta: float = 0.1):
        super().__init__()
        self.rank = int(rank)
        self.fourier_k = int(fourier_k)
        self.eta = float(eta)
        self.contract_embed = nn.Embedding(2, int(contract_dim))
        nn.init.zeros_(self.contract_embed.weight)
        in_dim = 2 * self.fourier_k + int(contract_dim)
        self.mlp = nn.Sequential(
            nn.Linear(in_dim, hidden), nn.Tanh(),
            nn.Linear(hidden, hidden), nn.Tanh(),
            nn.Linear(hidden, self.rank * self.rank),
        )
        nn.init.zeros_(self.mlp[-1].weight)
        nn.init.zeros_(self.mlp[-1].bias)

    def forward(self, lam, contract_present: bool) -> torch.Tensor:
        f = fourier_features(lam, self.fourier_k).reshape(-1)
        idx = torch.tensor(1 if contract_present else 0, device=f.device)
        c = self.contract_embed(idx)
        core = self.mlp(torch.cat([f, c])).reshape(self.rank, self.rank)
        eye = torch.eye(self.rank, device=core.device, dtype=core.dtype)
        return eye + self.eta * core

    def param_count(self) -> int:
        return sum(p.numel() for p in self.parameters())


class CNARAController(nn.Module):
    """Owns the single globally-shared CNaRA hypernetwork for one model.

    The training loop calls ``set_condition(lam, contract_present)`` once per
    step (before forward); every CNARALinear then uses the cached S. S is a
    plain tensor attribute (NOT a buffer/parameter): it is recomputed every
    step and needs no checkpointing — the hypernetwork weights are what get
    saved. Before the first set_condition, S = I (static-LoRA behavior).
    """

    def __init__(self, rank: int, fourier_k: int = 8, hidden: int = 64,
                 eta: float = 0.1):
        super().__init__()
        self.hypernet = CNARAHyperNet(rank, fourier_k=fourier_k,
                                      hidden=hidden, eta=eta)
        self._S = torch.eye(int(rank))          # cached core; I until set
        self.last_condition: tuple | None = None  # (lam, contract) — audit

    def set_condition(self, lam, contract_present: bool = False) -> torch.Tensor:
        """Recompute S for this step. Runs in grad mode: the hypernetwork
        LEARNS — do not wrap in torch.no_grad() during training."""
        S = self.hypernet(lam, bool(contract_present))
        self._S = S
        lam_f = float(torch.as_tensor(lam, dtype=torch.float32).reshape(-1)[0])
        self.last_condition = (lam_f, bool(contract_present))
        return S

    def core(self) -> torch.Tensor:
        return self._S


class CNARALinear(LoRALinear):
    """LoRA with a noise/contract-conditioned core: ΔW = scaling · B·S(λ,c)·A.

    Shares ONE CNARAController (the model's globally-shared hypernetwork)
    across all wrapped layers — the NaRA design. Step-0 behavior is exactly
    static LoRA (B is zero-init AND S = I at init).
    """

    def __init__(self, base: nn.Linear, controller: CNARAController,
                 rank: int = 8, alpha: float = 16.0):
        if not isinstance(controller, CNARAController):
            raise TypeError("controller must be a CNARAController")
        if controller.hypernet.rank != int(rank):
            raise ValueError(
                f"controller rank {controller.hypernet.rank} != adapter rank {rank}")
        # Bypass nn.Module.__setattr__: the controller must NOT be registered
        # as a submodule of every wrapper (that would duplicate its params in
        # state_dict once per layer and break the freeze-name logic). It is
        # registered exactly once, as model.cnara_controller.
        object.__setattr__(self, "controller", controller)
        super().__init__(base, rank=rank, alpha=alpha)

    def forward(self, x):
        base_out = self.base(x)
        S = self.controller.core().to(dtype=x.dtype)
        lora_out = (x @ self.lora_A.T @ S.T @ self.lora_B.T) * self.scaling
        return base_out + lora_out


def inject_cnara(model, rank: int = 8, alpha: float = 16.0,
                 target_modules=("qkv", "out"),
                 fourier_k: int = 8, hidden: int = 64,
                 eta: float = 0.1):
    """Replace target Linears with CNaRA wrappers + one shared controller.

    Registers ``model.cnara_controller`` (in state_dict, checkpointed).
    Freezes everything except adapter (lora_*) and hypernetwork params.
    Returns total trainable params (adapters + hypernetwork).
    """
    for block in model.layers:
        for name in target_modules:
            if isinstance(getattr(block.attn, name), LoRALinear):
                raise ValueError(
                    f"block already has a LoRA/CNaRA adapter on {name}: "
                    "refusing double injection")
    controller = CNARAController(rank=rank, fourier_k=fourier_k,
                                 hidden=hidden, eta=eta)
    model.cnara_controller = controller
    total = 0
    for block in model.layers:
        for name in target_modules:
            orig = getattr(block.attn, name)
            wrapped = CNARALinear(orig, controller, rank=rank, alpha=alpha)
            setattr(block.attn, name, wrapped)
            total += wrapped.trainable_params()
    for pname, p in model.named_parameters():
        if "lora_" not in pname and "cnara_controller" not in pname:
            p.requires_grad = False
    total += sum(p.numel() for p in controller.parameters()
                 if p.requires_grad)
    return total


def apply_cnara_condition(model, lam, contract_present: bool = False):
    """Set the CNaRA condition for the current step. Raises if the model has
    no CNaRA controller (i.e. inject_cnara was never called)."""
    controller = getattr(model, "cnara_controller", None)
    if controller is None:
        raise ValueError("model has no cnara_controller — call inject_cnara first")
    return controller.set_condition(lam, bool(contract_present))


def merge_cnara(model, lam, contract_present: bool = False):
    """Fold CNaRA adapters into base weights AT ONE FIXED CONDITION.

    Because S(λ, c) varies with the condition, deployment folding must pick
    the condition the deployed model will see most (e.g. lam ≈ expected mask
    ratio, contract = whether serving is contract-conditioned). The folded
    model is then a plain static network — no controller needed.
    """
    controller = getattr(model, "cnara_controller", None)
    if controller is None:
        raise ValueError("model has no cnara_controller — call inject_cnara first")
    with torch.no_grad():
        S = controller.set_condition(lam, bool(contract_present))
        for block in model.layers:
            for name in ("qkv", "out"):
                mod = getattr(block.attn, name)
                if isinstance(mod, CNARALinear):
                    # forward: x @ A.T @ S.T @ B.T == x @ (B@S@A).T, so the
                    # fold is W += scaling * (B@S@A) — no transpose.
                    delta = (mod.lora_B @ S @ mod.lora_A) * mod.scaling
                    mod.base.weight += delta
                    setattr(block.attn, name, mod.base)
    if hasattr(model, "cnara_controller"):
        delattr(model, "cnara_controller")
    return model
